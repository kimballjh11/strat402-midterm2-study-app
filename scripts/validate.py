#!/usr/bin/env python3
"""Coverage and schema check. Writes STATUS.generated.md. Exit code 1 if any in-scope objective is incomplete.
Usage: python3 scripts/validate.py [S15 S16 ...]   (no args = every build session in config.json)"""
import json, sys, glob, re
from pathlib import Path
HERE = Path(__file__).resolve().parent.parent
cfg = json.loads((HERE / "config.json").read_text())
objs = json.loads((HERE / "reference" / "objectives.json").read_text())
MIN = cfg["min_questions_per_objective"]
scope = {int(a.lstrip("S")) for a in sys.argv[1:]} or set(cfg["build_sessions"])

questions = []
for f in glob.glob(str(HERE / "content" / "questions" / "**" / "*.json"), recursive=True):
    data = json.loads(Path(f).read_text())
    questions += data if isinstance(data, list) else data.get("questions", [])
for f in glob.glob(str(HERE / "content" / "cases" / "*.json")):
    for c in json.loads(Path(f).read_text()):
        for p in c.get("parts", []): p.setdefault("case", c["id"]); questions.append(p)
gens = {}
for f in glob.glob(str(HERE / "content" / "generators" / "*.js")):
    import re
    for m in re.finditer(r"id:\s*[\"']([^\"']+)[\"'][^}]*?los:\s*\[([^\]]*)\]", Path(f).read_text(), re.S):
        for lo in re.findall(r"S\d+-\d+", m.group(2)): gens.setdefault(lo, []).append(m.group(1))

problems, rows, seen = [], [], set()
for q in questions:
    if q.get("id") in seen: problems.append(f"duplicate id {q.get('id')}")
    seen.add(q.get("id"))
    t = q.get("type")
    if not q.get("stem") or not q.get("explain"): problems.append(f"{q.get('id')}: missing stem or explanation")
    if t in ("mc", "tf", "multi"):
        ch, a = q.get("choices", []), q.get("answer")
        ok = isinstance(a, int) and 0 <= a < len(ch) or isinstance(a, list) and all(0 <= i < len(ch) for i in a)
        if len(ch) < 2 or not ok: problems.append(f"{q.get('id')}: bad choices or answer")
    elif t == "num":
        if not isinstance(q.get("answer"), (int, float)): problems.append(f"{q.get('id')}: numeric answer missing")
    else: problems.append(f"{q.get('id')}: unknown type {t}")
    if q.get("needs_review"): problems.append(f"{q.get('id')}: imported question flagged needs_review")

for o in objs:
    if o["session"] not in scope: continue
    lid = o["id"]
    lesson = HERE / "content" / "lessons" / f"{lid}.json"
    mine = [q for q in questions if lid in q.get("los", [])]
    n_concept = sum(1 for q in mine if q.get("kind") == "concept")
    n_apply = sum(1 for q in mine if q.get("kind") == "apply")
    n_calc = sum(1 for q in mine if q.get("kind") == "calc")
    n_gen = len(gens.get(lid, []))
    calc_lo = False
    if lesson.exists():
        L = json.loads(lesson.read_text()); calc_lo = bool(L.get("calc"))
        for k in ("title", "plain", "why", "definition", "traps", "sources"):
            if not L.get(k): problems.append(f"{lid}: lesson missing '{k}'")
        if not L.get("worked") : problems.append(f"{lid}: lesson has no worked example")
    need = []
    if not lesson.exists(): need.append("lesson")
    if len(mine) + 2 * n_gen < MIN: need.append(f"questions {len(mine)}+{n_gen}gen<{MIN}")
    if n_concept < 5: need.append("concept<5")
    if n_apply < 3: need.append("apply<3")
    if calc_lo and (n_calc < 4 or n_gen < 1): need.append("calc<4 or no generator")
    rows.append((lid, o["short"], "ok" if not need else "; ".join(need), len(mine), n_gen, n_concept, n_apply, n_calc))

# Slide ledger: every page of every slide deck in scope must map to objectives or carry a reason
led_f = HERE / "coverage" / "slide-ledger.json"
led = json.loads(led_f.read_text()) if led_f.exists() else {}
import subprocess
for n in sorted(scope):
    for pdf in sorted((HERE / "sources" / "raw" / f"S{n}").glob("*Slides*.pdf")):
        entry = led.get(f"S{n}", {}).get(pdf.name)
        if entry is None: problems.append(f"S{n}: slide ledger has no entry for {pdf.name}"); continue
        try:
            pages = int(re.search(r"Pages:\s+(\d+)", subprocess.run(["pdfinfo", str(pdf)], capture_output=True, text=True).stdout).group(1))
        except Exception: pages = 0
        for pg in range(1, pages + 1):
            e = entry.get(str(pg))
            if not e or (not e.get("los") and not e.get("reason")): problems.append(f"S{n}: {pdf.name} page {pg} has no objective and no reason")

lines = ["# STATUS (generated by scripts/validate.py)", "", "| LO | Objective | Result | Qs | Gens | Concept | Apply | Calc |", "|---|---|---|---|---|---|---|---|"]
lines += [f"| {r[0]} | {r[1][:48]} | {r[2]} | {r[3]} | {r[4]} | {r[5]} | {r[6]} | {r[7]} |" for r in rows]
todo = [r for r in rows if r[2] != "ok"]
lines += ["", f"Complete: {len(rows)-len(todo)} of {len(rows)} objectives in scope.", f"Next incomplete: {todo[0][0] if todo else 'none'}", "", "## Problems"] + (problems or ["none"])
(HERE / "STATUS.generated.md").write_text("\n".join(lines))
print("\n".join(lines[:4] + lines[-14:]))
sys.exit(1 if todo or problems else 0)
